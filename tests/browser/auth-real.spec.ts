import { expect, test, type Page } from '@playwright/test';
import { randomUUID } from 'node:crypto';
test.skip(!process.env.FRASIVO_TEST_URL, 'Estas pruebas necesitan el servidor y PostgreSQL de Docker.');
test.use({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
const nav = (page: Page) => page.getByRole('navigation', { name: 'Navegación móvil', exact: true });
async function login(page: Page, email: string, password: string) {
  await page.getByLabel('Correo electrónico').fill(email);
  await page.getByLabel('Contraseña', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
}
test('registro y login reales conservan avance entre navegadores y aíslan otras cuentas', async ({ page, browser }) => {
  const email = `browser-${randomUUID()}@example.test`, password = `Frasivo ${randomUUID()}`;
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Inicia sesión' })).toBeVisible();
  await page.screenshot({ path: 'test-results/auth-login-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Crear cuenta', exact: true }).click();
  await page.getByLabel('Correo electrónico').fill(email);
  await page.getByLabel('Contraseña', { exact: true }).fill(password);
  await page.getByLabel('Tu nombre').fill('Cuenta de prueba');
  await page.getByRole('radio', { name: /^Medicina/ }).check();
  await page.getByRole('radio', { name: /^Básico/ }).check();
  await page.getByRole('button', { name: 'Crear mi cuenta', exact: true }).click();
  await expect(page.getByText('Hola, Cuenta de prueba.', { exact: true })).toBeVisible();
  await nav(page).getByRole('button', { name: 'Practicar', exact: true }).click();
  const saved = page.waitForResponse(response => response.url().endsWith('/api/progress') && response.request().method() === 'PUT' && response.request().postDataJSON()?.value?.points === 10 && response.ok());
  await page.locator('.answer-option').filter({ hasText: 'Corazón' }).click(); await saved;
  await page.reload(); await expect(page.locator('.points')).toContainText('10 puntos');
  const second = await browser.newContext({ baseURL: process.env.FRASIVO_TEST_URL, viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  try {
    const other = await second.newPage(); await other.goto('/'); await login(other, email, password);
    await expect(other.locator('.points')).toContainText('10 puntos');
    await other.getByRole('button', { name: 'Editar perfil', exact: true }).click();
    await other.getByRole('radio', { name: /^Intermedio/ }).check();
    await other.getByRole('button', { name: 'Guardar perfil', exact: true }).click();
    await expect(other.getByText('Hola, Cuenta de prueba.', { exact: true })).toBeVisible();
    await page.reload(); await nav(page).getByRole('button', { name: 'Practicar', exact: true }).click();
    await expect(page.locator('.career-practice-context')).toContainText('Intermedio');
    await other.getByRole('button', { name: 'Editar perfil', exact: true }).click();
    await other.getByRole('button', { name: 'Cerrar sesión', exact: true }).click();
    await expect(other.getByRole('heading', { name: 'Inicia sesión' })).toBeVisible();
    await login(other, email, 'a wrong password 123'); await expect(other.getByRole('alert')).toContainText('incorrectos');
    await other.getByRole('button', { name: 'Crear cuenta', exact: true }).click();
    await other.getByLabel('Correo electrónico').fill(`other-${randomUUID()}@example.test`);
    await other.getByLabel('Contraseña', { exact: true }).fill(password);
    await other.getByLabel('Tu nombre').fill('Otra cuenta');
    await other.getByRole('radio', { name: /^Ingeniería de Sistemas/ }).check();
    await other.getByRole('radio', { name: /^Avanzado/ }).check();
    await other.getByRole('button', { name: 'Crear mi cuenta', exact: true }).click();
    await expect(other.locator('.points')).toContainText('0 puntos');
    await nav(other).getByRole('button', { name: 'Explora objetos', exact: true }).click();
    await expect(other.getByRole('heading', { name: 'Array', exact: true })).toBeVisible();
    await expect(other.locator('.object-canvas')).toHaveAttribute('data-rendered', 'array');
    await page.reload(); await expect(page.locator('.points')).toContainText('10 puntos');
  } finally { await second.close(); }
  expect(errors).toEqual([]);
});
test('un perfil local falsificado no sustituye una sesión de servidor', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('frasivo-profile:v1', JSON.stringify({ version: 1, name: 'Fake', career: 'systems', level: 'advanced' })));
  await page.goto('/'); await expect(page.getByRole('heading', { name: 'Inicia sesión' })).toBeVisible();
  await expect(page.getByText('Hola, Fake.', { exact: true })).toHaveCount(0);
  const response = await page.request.get('/api/me'); expect(response.status()).toBe(401);
});
test('una sesión perdida vuelve al login sin reenviar respuestas a otra cuenta', async ({ page, context }) => {
  const email = `expiry-${randomUUID()}@example.test`, password = `Frasivo ${randomUUID()}`;
  await page.goto('/'); await page.getByRole('button', { name: 'Crear cuenta', exact: true }).click();
  await page.getByLabel('Correo electrónico').fill(email); await page.getByLabel('Contraseña', { exact: true }).fill(password);
  await page.getByLabel('Tu nombre').fill('Sesión temporal');
  await page.getByRole('radio', { name: /^Medicina/ }).check(); await page.getByRole('radio', { name: /^Básico/ }).check();
  await page.getByRole('button', { name: 'Crear mi cuenta', exact: true }).click();
  await expect(page.getByText('Hola, Sesión temporal.', { exact: true })).toBeVisible();
  await expect.poll(async () => Object.keys((await (await page.request.get('/api/progress')).json()).progress).length).toBe(2);
  await nav(page).getByRole('button', { name: 'Practicar', exact: true }).click();
  await context.clearCookies();
  await page.locator('.answer-option').filter({ hasText: 'Corazón' }).click();
  await expect(page.getByRole('heading', { name: 'Inicia sesión' })).toBeVisible();
  await expect(page.getByRole('status')).toContainText('sesión cambió o caducó');
  await login(page, email, password); await expect(page.locator('.points')).toContainText('0 puntos');
  await context.clearCookies();
  await page.getByRole('button', { name: 'Editar perfil', exact: true }).click();
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Inicia sesión' })).toBeVisible();
});
